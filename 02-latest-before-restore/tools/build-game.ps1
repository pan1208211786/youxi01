# Build the browser-ready file from the modular source files.
# Keep gameplay edits in src; this script only creates game.bundle.js.
$sourceFiles = @(
  'src/config/GameConfig.js',
  'src/constants/GameConstants.js',
  'src/core/SaveManager.js',
  'src/core/GameState.js',
  'src/core/EventBus.js',
  'src/utils/GridUtils.js',
  'src/data/levels.js',
  'src/entities/Player.js',
  'src/systems/AudioManager.js',
  'src/systems/FullscreenManager.js',
  'src/systems/Board.js',
  'src/ui/UIFactory.js',
  'src/ui/LoadingDomUI.js',
  'src/ui/TutorialDomUI.js',
  'src/ui/LevelSelectDomUI.js',
  'src/ui/MenuDomUI.js',
  'src/scenes/BaseScene.js',
  'src/scenes/BootScene.js',
  'src/scenes/PreloadScene.js',
  'src/scenes/MainMenuScene.js',
  'src/scenes/TutorialScene.js',
  'src/scenes/LevelSelectScene.js',
  'src/scenes/SettingsScene.js',
  'src/scenes/GameScene.js',
  'src/main.js'
)

$bundle = @('/* Generated by tools/build-game.ps1. Edit files in src instead. */')
foreach ($file in $sourceFiles) {
  # Remove module markers while preserving the source and its Chinese comments.
  $content = Get-Content -Raw -Encoding UTF8 $file
  $content = [regex]::Replace($content, '(?m)^import .*?;\r?\n', '')
  $content = $content -replace '(?m)^export default ', ''
  $content = $content -replace '(?m)^export ', ''
  $bundle += "`n/* ===== $file ===== */`n$content"
}

Set-Content -Path 'game.bundle.js' -Value ($bundle -join "`n") -Encoding UTF8
Write-Host 'game.bundle.js has been updated.'
